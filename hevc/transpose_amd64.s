//go:build amd64 && !noasm

#include "textflag.h"

// func transpose8AVX2(dst, src *int32, n int)
//
// Transposes an n by n block of int32 in eight by eight tiles, the usual
// unpack-then-cross-lane sequence.
TEXT ·transpose8AVX2(SB), NOSPLIT, $0-24
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ n+16(FP), CX

	MOVQ CX, R8
	SHLQ $2, R8

	XORQ R9, R9

yloop:
	XORQ R10, R10

xloop:
	MOVQ R9, AX
	IMULQ R8, AX
	LEAQ (SI)(AX*1), R11
	LEAQ (R11)(R10*4), R11

	MOVQ R10, AX
	IMULQ R8, AX
	LEAQ (DI)(AX*1), R12
	LEAQ (R12)(R9*4), R12

	VMOVDQU (R11), Y0
	ADDQ    R8, R11
	VMOVDQU (R11), Y1
	ADDQ    R8, R11
	VMOVDQU (R11), Y2
	ADDQ    R8, R11
	VMOVDQU (R11), Y3
	ADDQ    R8, R11
	VMOVDQU (R11), Y4
	ADDQ    R8, R11
	VMOVDQU (R11), Y5
	ADDQ    R8, R11
	VMOVDQU (R11), Y6
	ADDQ    R8, R11
	VMOVDQU (R11), Y7

	VPUNPCKLDQ Y1, Y0, Y8
	VPUNPCKHDQ Y1, Y0, Y9
	VPUNPCKLDQ Y3, Y2, Y10
	VPUNPCKHDQ Y3, Y2, Y11
	VPUNPCKLDQ Y5, Y4, Y12
	VPUNPCKHDQ Y5, Y4, Y13
	VPUNPCKLDQ Y7, Y6, Y14
	VPUNPCKHDQ Y7, Y6, Y15

	VPUNPCKLQDQ Y10, Y8, Y0
	VPUNPCKHQDQ Y10, Y8, Y1
	VPUNPCKLQDQ Y11, Y9, Y2
	VPUNPCKHQDQ Y11, Y9, Y3
	VPUNPCKLQDQ Y14, Y12, Y4
	VPUNPCKHQDQ Y14, Y12, Y5
	VPUNPCKLQDQ Y15, Y13, Y6
	VPUNPCKHQDQ Y15, Y13, Y7

	VPERM2I128 $0x20, Y4, Y0, Y8
	VPERM2I128 $0x20, Y5, Y1, Y9
	VPERM2I128 $0x20, Y6, Y2, Y10
	VPERM2I128 $0x20, Y7, Y3, Y11
	VPERM2I128 $0x31, Y4, Y0, Y12
	VPERM2I128 $0x31, Y5, Y1, Y13
	VPERM2I128 $0x31, Y6, Y2, Y14
	VPERM2I128 $0x31, Y7, Y3, Y15

	VMOVDQU Y8, (R12)
	ADDQ    R8, R12
	VMOVDQU Y9, (R12)
	ADDQ    R8, R12
	VMOVDQU Y10, (R12)
	ADDQ    R8, R12
	VMOVDQU Y11, (R12)
	ADDQ    R8, R12
	VMOVDQU Y12, (R12)
	ADDQ    R8, R12
	VMOVDQU Y13, (R12)
	ADDQ    R8, R12
	VMOVDQU Y14, (R12)
	ADDQ    R8, R12
	VMOVDQU Y15, (R12)

	ADDQ $8, R10
	CMPQ R10, CX
	JLT  xloop

	ADDQ $8, R9
	CMPQ R9, CX
	JLT  yloop

	VZEROUPPER
	RET
