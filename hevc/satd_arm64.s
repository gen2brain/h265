	VSUB V7.H8, V6.H8, V15.H8

	ABS8H(8, 8)
	UADALP4S(16, 8)
	ABS8H(9, 9)
	UADALP4S(16, 9)
	ABS8H(10, 10)
	UADALP4S(16, 10)
