#include "textflag.h"

#define ABS8H(Vd, Vn)    WORD $(0x4e60b800 | ((Vn) << 5) | (Vd))
#define UADALP4S(Vd, Vn) WORD $(0x6e606800 | ((Vn) << 5) | (Vd))

// func satd16x8NEON(src *uint8, srcStride int, pred *uint8, predStride int) int64
//
// satd over a sixteen wide and eight tall strip, one 8x8 at a time: a row of
// eight int16 is exactly one register, and both halves accumulate into the same
// pairwise sum. Differences reach 255 and each pass scales by eight, which
// int16 holds.
TEXT ·satd16x8NEON(SB), NOSPLIT, $0-40
	MOVD src+0(FP), R0
	MOVD srcStride+8(FP), R1
	MOVD pred+16(FP), R2
	MOVD predStride+24(FP), R3

	VMOVI $0, V16.B16

	MOVD $2, R4

half:
	MOVD R0, R5
	MOVD R2, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V0.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V0.H8, V0.H8
	ADD   R1, R5
	ADD   R3, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V1.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V1.H8, V1.H8
	ADD   R1, R5
	ADD   R3, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V2.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V2.H8, V2.H8
	ADD   R1, R5
	ADD   R3, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V3.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V3.H8, V3.H8
	ADD   R1, R5
	ADD   R3, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V4.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V4.H8, V4.H8
	ADD   R1, R5
	ADD   R3, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V5.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V5.H8, V5.H8
	ADD   R1, R5
	ADD   R3, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V6.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V6.H8, V6.H8
	ADD   R1, R5
	ADD   R3, R6

	VLD1  (R5), [V17.B8]
	VUXTL V17.B8, V7.H8
	VLD1  (R6), [V17.B8]
	VUXTL V17.B8, V17.H8
	VSUB  V17.H8, V7.H8, V7.H8

	VADD V4.H8, V0.H8, V8.H8
	VSUB V4.H8, V0.H8, V12.H8
	VADD V5.H8, V1.H8, V9.H8
	VSUB V5.H8, V1.H8, V13.H8
	VADD V6.H8, V2.H8, V10.H8
	VSUB V6.H8, V2.H8, V14.H8
	VADD V7.H8, V3.H8, V11.H8
	VSUB V7.H8, V3.H8, V15.H8

	VADD V10.H8, V8.H8, V0.H8
