	VADD V15.H8, V13.H8, V5.H8
	VSUB V14.H8, V12.H8, V6.H8
	VSUB V15.H8, V13.H8, V7.H8

	VADD V1.H8, V0.H8, V8.H8
	VSUB V1.H8, V0.H8, V9.H8
	VADD V3.H8, V2.H8, V10.H8
	VSUB V3.H8, V2.H8, V11.H8
	VADD V5.H8, V4.H8, V12.H8
	VSUB V5.H8, V4.H8, V13.H8
	VADD V7.H8, V6.H8, V14.H8
	VSUB V7.H8, V6.H8, V15.H8

	// Transpose, so the second pass lands on the rows.
	VTRN1 V9.H8, V8.H8, V0.H8
	VTRN2 V9.H8, V8.H8, V1.H8
	VTRN1 V11.H8, V10.H8, V2.H8
	VTRN2 V11.H8, V10.H8, V3.H8
	VTRN1 V13.H8, V12.H8, V4.H8
	VTRN2 V13.H8, V12.H8, V5.H8
