	ABS8H(14, 14)
	UADALP4S(16, 14)
	ABS8H(15, 15)
	UADALP4S(16, 15)

	ADD $8, R0
	ADD $8, R2

	SUB  $1, R4
	CBNZ R4, half

	VADDV V16.S4, V17
	VMOV  V17.S[0], R5

	MOVD R5, ret+32(FP)
	RET
