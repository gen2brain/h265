#include "textflag.h"

// func satd16x8AVX2(src *uint8, srcStride int, pred *uint8, predStride int) int64
//
// satd over a sixteen wide and eight tall strip. Y0 to Y7 hold the rows as
// sixteen int16, one 8x8 per lane, and every butterfly and unpack is lane local
// so the two ride through together. Differences reach 255 and each pass scales
// by eight, which int16 holds.
TEXT ·satd16x8AVX2(SB), NOSPLIT, $0-40
	MOVQ src+0(FP), SI
	MOVQ srcStride+8(FP), R8
	MOVQ pred+16(FP), DI
	MOVQ predStride+24(FP), R9

	VPMOVZXBW (SI), Y0
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y0, Y0

	ADDQ      R8, SI
	ADDQ      R9, DI
	VPMOVZXBW (SI), Y1
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y1, Y1

	ADDQ      R8, SI
	ADDQ      R9, DI
	VPMOVZXBW (SI), Y2
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y2, Y2

	ADDQ      R8, SI
	ADDQ      R9, DI
	VPMOVZXBW (SI), Y3
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y3, Y3

	ADDQ      R8, SI
	ADDQ      R9, DI
	VPMOVZXBW (SI), Y4
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y4, Y4

	ADDQ      R8, SI
	ADDQ      R9, DI
	VPMOVZXBW (SI), Y5
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y5, Y5

	ADDQ      R8, SI
	ADDQ      R9, DI
	VPMOVZXBW (SI), Y6
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y6, Y6

	ADDQ      R8, SI
	ADDQ      R9, DI
	VPMOVZXBW (SI), Y7
	VPMOVZXBW (DI), Y8
	VPSUBW    Y8, Y7, Y7

	VPADDW Y4, Y0, Y8
	VPSUBW Y4, Y0, Y12
	VPADDW Y5, Y1, Y9
	VPSUBW Y5, Y1, Y13
	VPADDW Y6, Y2, Y10
	VPSUBW Y6, Y2, Y14
	VPADDW Y7, Y3, Y11
	VPSUBW Y7, Y3, Y15

	VPADDW Y10, Y8, Y0
	VPADDW Y11, Y9, Y1
	VPSUBW Y10, Y8, Y2
	VPSUBW Y11, Y9, Y3
	VPADDW Y14, Y12, Y4
	VPADDW Y15, Y13, Y5
	VPSUBW Y14, Y12, Y6
	VPSUBW Y15, Y13, Y7

	VPADDW Y1, Y0, Y8
	VPSUBW Y1, Y0, Y9
	VPADDW Y3, Y2, Y10
	VPSUBW Y3, Y2, Y11
	VPADDW Y5, Y4, Y12
	VPSUBW Y5, Y4, Y13
	VPADDW Y7, Y6, Y14
	VPSUBW Y7, Y6, Y15

	// Transpose within each lane, so the second pass lands on the rows.
	VPUNPCKLWD Y9, Y8, Y0
	VPUNPCKHWD Y9, Y8, Y1
	VPUNPCKLWD Y11, Y10, Y2
	VPUNPCKHWD Y11, Y10, Y3
	VPUNPCKLWD Y13, Y12, Y4
	VPUNPCKHWD Y13, Y12, Y5
	VPUNPCKLWD Y15, Y14, Y6
	VPUNPCKHWD Y15, Y14, Y7

	VPUNPCKLDQ Y2, Y0, Y8
	VPUNPCKHDQ Y2, Y0, Y9
	VPUNPCKLDQ Y3, Y1, Y10
	VPUNPCKHDQ Y3, Y1, Y11
	VPUNPCKLDQ Y6, Y4, Y12
	VPUNPCKHDQ Y6, Y4, Y13
	VPUNPCKLDQ Y7, Y5, Y14
	VPUNPCKHDQ Y7, Y5, Y15

	VPUNPCKLQDQ Y12, Y8, Y0
	VPUNPCKHQDQ Y12, Y8, Y1
	VPUNPCKLQDQ Y13, Y9, Y2
	VPUNPCKHQDQ Y13, Y9, Y3
	VPUNPCKLQDQ Y14, Y10, Y4
	VPUNPCKHQDQ Y14, Y10, Y5
	VPUNPCKLQDQ Y15, Y11, Y6
	VPUNPCKHQDQ Y15, Y11, Y7

	VPADDW Y4, Y0, Y8
	VPSUBW Y4, Y0, Y12
	VPADDW Y5, Y1, Y9
	VPSUBW Y5, Y1, Y13
	VPADDW Y6, Y2, Y10
	VPSUBW Y6, Y2, Y14
	VPADDW Y7, Y3, Y11
	VPSUBW Y7, Y3, Y15

	VPADDW Y10, Y8, Y0
	VPADDW Y11, Y9, Y1
	VPSUBW Y10, Y8, Y2
	VPSUBW Y11, Y9, Y3
	VPADDW Y14, Y12, Y4
	VPADDW Y15, Y13, Y5
	VPSUBW Y14, Y12, Y6
	VPSUBW Y15, Y13, Y7

	VPADDW Y1, Y0, Y8
	VPSUBW Y1, Y0, Y9
	VPADDW Y3, Y2, Y10
	VPSUBW Y3, Y2, Y11
	VPADDW Y5, Y4, Y12
	VPSUBW Y5, Y4, Y13
	VPADDW Y7, Y6, Y14
	VPSUBW Y7, Y6, Y15

	// The pairwise multiply by one widens as it adds.
	MOVL         $0x00010001, AX
	VMOVD        AX, X1
	VPBROADCASTD X1, Y1

	VPABSW  Y8, Y8
	VPMADDWD Y1, Y8, Y0

	VPABSW   Y9, Y9
	VPMADDWD Y1, Y9, Y9
	VPADDD   Y9, Y0, Y0

	VPABSW   Y10, Y10
	VPMADDWD Y1, Y10, Y10
	VPADDD   Y10, Y0, Y0

	VPABSW   Y11, Y11
	VPMADDWD Y1, Y11, Y11
	VPADDD   Y11, Y0, Y0

	VPABSW   Y12, Y12
	VPMADDWD Y1, Y12, Y12
	VPADDD   Y12, Y0, Y0

	VPABSW   Y13, Y13
	VPMADDWD Y1, Y13, Y13
	VPADDD   Y13, Y0, Y0

	VPABSW   Y14, Y14
	VPMADDWD Y1, Y14, Y14
	VPADDD   Y14, Y0, Y0

	VPABSW   Y15, Y15
	VPMADDWD Y1, Y15, Y15
	VPADDD   Y15, Y0, Y0

	VEXTRACTI128 $1, Y0, X1
	VPADDD       X1, X0, X0
	VPSHUFD      $0x4e, X0, X1
	VPADDD       X1, X0, X0
	VPSHUFD      $0xb1, X0, X1
	VPADDD       X1, X0, X0

	VMOVD   X0, AX
	MOVLQZX AX, AX
	MOVQ    AX, ret+32(FP)

	VZEROUPPER
	RET
